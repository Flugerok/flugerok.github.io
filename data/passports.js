/*
  passports.js
  ------------
  "Паспорт" каждого изготовленного флюгера — отдельная запись на каждый
  физический экземпляр, который вы сделали и промаркировали уникальным
  номером.

  НЕ ПУТАТЬ с js/products.js:
  - products.js  — товары на продажу (модели, которые можно заказать);
  - passports.js — история уже изготовленных конкретных экземпляров,
                    у каждого из которых свой номер, нанесённый на сам
                    флюгер (например лазером или гравировкой).

  Как это работает: человек находит флюгер (свой или чужой) через много
  лет, видит на нём номер, вбивает его в Google/Яндекс — и попадает на
  отдельную страницу именно этого экземпляра с датой изготовления
  (и тем, сколько дней прошло с этой даты — считается автоматически)
  и фотографиями на момент создания, которые открываются в полноэкранном
  режиме с перелистыванием. Эти страницы НЕ связаны ссылками с
  остальным сайтом специально — их может найти только тот, кто уже
  знает точный номер.

  Как добавить новый паспорт
  ----------------------------
  1. Скопируйте один из объектов в массиве PASSPORTS ниже.
  2. Заполните поля (описание — см. дальше).
  3. Запустите в терминале, из папки сайта:
       node build-passports.js
     Скрипт создаст файл passport/ВАШ_НОМЕР.html.
  4. Закоммитьте и запушьте новый файл вместе с остальным сайтом.
  5. Важный шаг именно для этих страниц — отправьте её на индексацию
     вручную:
       - Google Search Console → "Проверка URL" → вставить адрес
         страницы → "Запросить индексирование";
       - Яндекс.Вебмастер → "Индексирование" → "Переобход страниц" →
         вставить адрес.
     Мы специально НЕ добавляем эти страницы в sitemap.xml — иначе
     список вообще всех выданных номеров был бы виден любому, кто
     откроет этот файл. Ручная отправка через Search Console/Вебмастер
     сохраняет тот же результат (страница попадает в индекс), но не
     раскрывает остальные номера.

  ОПИСАНИЕ ПОЛЕЙ
  ---------------
  number   — тот самый десятизначный номер, который нанесён на флюгер.
             Он же станет именем файла: passport/NUMBER.html.
             Старайтесь не путать похожие символы при составлении
             номеров (например буква O и цифра 0, буква I и цифра 1) —
             иначе владельцу будет сложно ввести номер без ошибки.
  date     — дата изготовления в формате ГГГГ-ММ-ДД (например
             "2026-09-01" — это 1 сентября 2026). Именно в таком виде,
             без слов, чтобы дату понимал не только человек, но и
             скрипт: build-passports.js сам превратит её в красивую
             русскую фразу ("1 сентября 2026 года") на странице, а
             браузер посетителя посчитает по ней, сколько дней прошло
             с изготовления.
  modelId  — необязательно: id модели из js/products.js (например
             "petuh"), если хотите дать на странице ссылку "Такая же
             модель есть в каталоге". Если оставить null — ссылки не
             будет.
  photos   — фотографии этого конкретного экземпляра на момент
             изготовления. Можно одну, можно несколько — все попадут
             в галерею с полноэкранным просмотром и перелистыванием.

  ВАЖНО О ПРИВАТНОСТИ: не указывайте здесь имя, телефon, адрес или
  любые другие данные покупателя. Эти страницы находятся в открытом
  доступе и индексируются поисковиками бессрочно — здесь должна быть
  информация только об изделии, не о человеке.
*/

